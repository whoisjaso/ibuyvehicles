/*
  The iBuy Vehicles emblem, a faithful vector replica of Mark's current logo
  (public/brand/emblem-original.svg, generated by scripts/build_logo.py from
  public/brand/original-logo.png). A refined alternative lives in
  public/brand/emblem.svg for Mark to compare.
*/
export function Emblem({ size = 40, className = "" }: { size?: number; className?: string }) {
  // eslint-disable-next-line @next/next/no-img-element
  return <img src="/brand/emblem-original.svg" alt="" aria-hidden width={Math.round(size * 1.34)} height={size} className={className} />;
}

/** Wordmark: the emblem is the only colour; the name is set quietly beside it. */
export function Wordmark({ className = "", inverse = false }: { className?: string; inverse?: boolean }) {
  return (
    <span className={`inline-flex items-center gap-3 whitespace-nowrap ${className}`}>
      <Emblem size={30} className="h-[26px] w-auto md:h-[30px]" />
      <span className={`text-[1.06rem] font-semibold uppercase tracking-[0.24em] ${inverse ? "text-white" : "text-ink"}`}>iBuy Vehicles</span>
    </span>
  );
}
